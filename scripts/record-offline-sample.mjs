// Records one real Open-Meteo Air Quality response for Johar Town / Riphah
// and writes it to lib/offlineSample.ts as the bundled fallback (R9.1).
//
// Usage: npm run record:sample
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const ZONE = { id: "riphah_johar", lat: 31.4697, lon: 74.2728 };

const params = new URLSearchParams({
  latitude: String(ZONE.lat),
  longitude: String(ZONE.lon),
  current: "us_aqi,pm2_5,pm10,carbon_monoxide,nitrogen_dioxide",
  hourly: "us_aqi,pm2_5,pm10,uv_index",
  timezone: "Asia/Karachi",
  forecast_days: "1",
});
const url = `https://air-quality-api.open-meteo.com/v1/air-quality?${params}`;

const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
if (!res.ok) {
  console.error(`Open-Meteo returned HTTP ${res.status}`);
  process.exit(1);
}
const raw = await res.json();

const nonNull = (raw.hourly?.pm2_5 ?? []).filter((v) => typeof v === "number").length;
if (raw.hourly?.time?.length !== 24 || nonNull < 12) {
  console.error(`Response failed validation: ${raw.hourly?.time?.length} hours, ${nonNull} non-null pm2_5`);
  process.exit(1);
}

const recordedAt = new Date().toISOString();
const out = `// AUTO-GENERATED by scripts/record-offline-sample.mjs — do not edit by hand.
// A real Open-Meteo Air Quality API response for ${ZONE.id} (${ZONE.lat}, ${ZONE.lon}),
// recorded ${recordedAt}. Used only when the live API fails (R9.1) and always
// labelled OFFLINE SAMPLE in the UI.
//
// Source: ${url}

export const OFFLINE_SAMPLE_RECORDED_AT = ${JSON.stringify(recordedAt)};
export const OFFLINE_SAMPLE_ZONE = ${JSON.stringify(ZONE.id)};

export const OFFLINE_SAMPLE_RAW = ${JSON.stringify(raw, null, 2)} as const;
`;

const target = fileURLToPath(new URL("../lib/offlineSample.ts", import.meta.url));
await writeFile(target, out, "utf8");
console.log(`Wrote ${target}`);
console.log(`current: AQI ${raw.current.us_aqi}, PM2.5 ${raw.current.pm2_5} µg/m³ at ${raw.current.time}`);
console.log(`hourly: ${nonNull}/24 non-null pm2_5`);
